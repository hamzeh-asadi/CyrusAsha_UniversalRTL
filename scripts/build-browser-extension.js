#!/usr/bin/env node
/*
 * Build Chrome / Firefox WebExtensions from shared sources.
 *
 * The browser extension does not maintain a second RTL engine: this script copies
 * src/engine/rtl-engine.js into each package and generates only the browser
 * manifests and a tiny shared site list. The ZIP writer is the project's own
 * zero-dependency writer in tools/zip.js.
 *
 * این اسکریپت از یک موتور مشترک، بسته‌ی Chrome و Firefox می‌سازد. موتور RTL
 * کپی جداگانه و دست‌کاری‌شده ندارد؛ فقط manifest مرورگرها و فهرست سایت‌ها
 * ساخته می‌شوند. ساخت ZIP هم با ابزار داخلی پروژه و بدون وابستگی انجام می‌شود.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { createZip } = require('../tools/zip');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'browser-extension');
const OUTPUT = path.join(ROOT, 'release', 'browser');
const ENGINE = path.join(ROOT, 'src', 'engine', 'rtl-engine.js');
const VERSION = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
const PRODUCT_NAME = 'CyrusAsha_UniversalRTL';
const SITE_LIST = JSON.parse(fs.readFileSync(path.join(SOURCE, 'sites.json'), 'utf8'));

const COMMON_FILES = [
  'background.js',
  'bootstrap.js',
  'content.js',
  'popup.html',
  'popup.css',
  'popup.js'
];

function uniqueMatches() {
  const matches = [];
  SITE_LIST.forEach((site) => site.matches.forEach((match) => {
    if (!matches.includes(match)) matches.push(match);
  }));
  return matches;
}

/* Create parent folders before copying a file, so the same build works on
 * Windows, macOS, and Linux without relying on shell mkdir/cp commands. */
function copyFile(source, destination) {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(source, destination);
}

function copyFolder(source, destination) {
  if (!fs.existsSync(source)) return;
  for (const item of fs.readdirSync(source, { withFileTypes: true })) {
    const from = path.join(source, item.name);
    const to = path.join(destination, item.name);
    if (item.isDirectory()) copyFolder(from, to);
    else if (item.isFile()) copyFile(from, to);
  }
}

/* One small list drives both the popup checkboxes and content-script site ID.
 * Keeping names and match rules together prevents a UI/permission mismatch. */
function siteConfigScript() {
  return [
    '/* Generated by scripts/build-browser-extension.js from browser-extension/sites.json.',
    ' * Keep this generated copy in the package; edit sites.json, then rebuild. */',
    'window.RTL_UNIVERSAL_SITES = ' + JSON.stringify(SITE_LIST, null, 2) + ';',
    ''
  ].join('\n');
}

function manifestFor(browserName) {
  const matches = uniqueMatches();
  const manifest = {
    manifest_version: 3,
    name: '__MSG_extName__',
    short_name: '__MSG_extShortName__',
    description: '__MSG_extDescription__',
    version: VERSION,
    default_locale: 'en',
    minimum_chrome_version: '109',
    icons: {
      '16': 'icons/rtl-16.png',
      '32': 'icons/rtl-32.png',
      '48': 'icons/rtl-48.png',
      '128': 'icons/rtl-128.png'
    },
    action: {
      default_title: '__MSG_actionTitle__',
      default_popup: 'popup.html',
      default_icon: {
        '16': 'icons/rtl-16.png',
        '32': 'icons/rtl-32.png'
      }
    },
    permissions: ['storage', 'scripting'],
    optional_host_permissions: ['https://*/*'],
    content_scripts: [{
      // Static matches remain limited to the built-in chat list. Custom domains
      // are granted one at a time and registered by background.js at runtime.
      matches,
      js: ['site-config.js', 'bootstrap.js', 'rtl-engine.js', 'content.js'],
      run_at: 'document_start',
      all_frames: false
    }]
  };

  if (browserName === 'firefox') {
    // Firefox MV3 uses an event page; Chrome MV3 uses a service worker.
    manifest.background = { scripts: ['background.js'] };
    manifest.browser_specific_settings = {
      gecko: {
        id: 'rtl-universal@hamzeh-asadi',
        // The no-data-collection declaration is supported starting in Firefox 140.
        strict_min_version: '140.0',
        data_collection_permissions: { required: ['none'] }
      },
      // Firefox for Android gained this consent manifest key in version 142.
      gecko_android: { strict_min_version: '142.0' }
    };
    delete manifest.minimum_chrome_version;
  } else {
    manifest.background = { service_worker: 'background.js' };
  }
  return manifest;
}

function collectZipEntries(folder) {
  const entries = [];
  function walk(current, relative) {
    for (const item of fs.readdirSync(current, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const absolute = path.join(current, item.name);
      const name = path.posix.join(relative, item.name);
      if (item.isDirectory()) walk(absolute, name);
      else if (item.isFile()) entries.push({ name, data: fs.readFileSync(absolute) });
    }
  }
  walk(folder, '');
  return entries;
}

function buildVariant(browserName) {
  const outDir = path.join(OUTPUT, browserName + '-unpacked');
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  COMMON_FILES.forEach((file) => copyFile(path.join(SOURCE, file), path.join(outDir, file)));
  copyFile(ENGINE, path.join(outDir, 'rtl-engine.js'));
  copyFolder(path.join(SOURCE, '_locales'), path.join(outDir, '_locales'));
  copyFolder(path.join(SOURCE, 'icons'), path.join(outDir, 'icons'));
  fs.writeFileSync(path.join(outDir, 'site-config.js'), siteConfigScript(), 'utf8');
  fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(manifestFor(browserName), null, 2) + '\n', 'utf8');

  const suffix = browserName === 'firefox' ? '.xpi' : '.zip';
  const title = browserName === 'firefox' ? 'Firefox' : 'Chrome';
  const filename = PRODUCT_NAME + '-' + VERSION + '-' + title + suffix;
  const packagePath = path.join(OUTPUT, filename);
  createZip(collectZipEntries(outDir), packagePath);
  return { outDir, packagePath, filename };
}

function main() {
  fs.mkdirSync(OUTPUT, { recursive: true });
  const chrome = buildVariant('chrome');
  const firefox = buildVariant('firefox');
  console.log('Chrome extension folder: release/browser/chrome-unpacked');
  console.log('Chrome Web Store / Edge package: release/browser/' + chrome.filename);
  console.log('Firefox add-on package: release/browser/' + firefox.filename);
  console.log('Web sites in both packages: ' + uniqueMatches().length + ' exact HTTPS match patterns');
}

if (require.main === module) {
  try { main(); }
  catch (error) { console.error('Browser-extension build failed: ' + error.stack); process.exit(1); }
}

module.exports = { main, manifestFor, uniqueMatches, siteConfigScript };
